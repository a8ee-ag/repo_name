"""Задача 6: пассажиры, возраст которых больше 44 лет."""

import pandas as pd


def older_than(df: pd.DataFrame, age: float = 44) -> pd.DataFrame:
    """Строки таблицы, где Age строго больше указанного возраста.

    df["Age"] > age даёт булеву маску (True/False на каждую строку),
    а df[маска] оставляет только строки с True.
    Пассажиры с пропущенным возрастом сюда не попадут: сравнение
    с NaN всегда даёт False.
    """
    return df[df["Age"] > age]


def run(df: pd.DataFrame) -> None:
    print("--- Пассажиры старше 44 лет ---")
    print(older_than(df, 44))


def younger_males(df: pd.DataFrame, age: float = 44) -> pd.DataFrame:
    """Мужчины, возраст которых меньше указанного.

    Условие Age > 0 отсекает нулевой возраст, а вместе с ним и пропуски:
    сравнение NaN с числом всегда даёт False, поэтому пассажиры
    с неизвестным возрастом в выборку не попадают.

    Условия объединяются через & (поэлементное «и»), каждое обязательно
    в своих скобках — у & приоритет выше, чем у сравнений.
    """
    return df[(df["Age"] > 0) & (df["Age"] < age) & (df["Sex"] == "male")]


def run_younger_males(df: pd.DataFrame) -> None:
    print("--- Мужчины младше 44 лет (без нулевого и неизвестного возраста) ---")
    print(younger_males(df, 44))
